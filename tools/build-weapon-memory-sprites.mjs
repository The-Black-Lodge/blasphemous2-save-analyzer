import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const [
  rippedDir = path.join(
    __dirname,
    "../../ripped/Assets/#Art/Sprites/UI/WeaponMemories",
  ),
  outJson = path.join(__dirname, "../src/data/weapon-memory-sprites.json"),
  outCss = path.join(__dirname, "../src/styles/weapon-memory-sprites.css"),
  publicDir = path.join(__dirname, "../public/sprites"),
  assetBase = "/blasphemous2-save-analyzer/",
  scaleRaw = "1",
] = process.argv.slice(2)

const scale = Number(scaleRaw)

const sheetId = "weapon-memories-spritesheet"
const sheetFile = path.join(rippedDir, `${sheetId}.png`)

// Five arsenal weapons on weapon-memories-spritesheet.png (not unlock variants).
const includePatterns = [
  /^weapon-memories-censer-image-big$/,
  /^weapon-memories-sword-image-big$/,
  /^weapon-memories-rapier-image-big$/,
  /^weapon-memories-meaculpa-image-big$/,
  /^weapon-memories-whip-image-big$/,
]

function pngSize(file) {
  const buf = fs.readFileSync(file)
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

function spriteClassName(name) {
  const match = name.match(/^weapon-memories-(.+)-image-big$/)
  return match?.[1] ?? name
}

if (!fs.existsSync(sheetFile)) {
  console.error("Missing atlas:", sheetFile)
  process.exit(1)
}

const atlas = { [sheetId]: pngSize(sheetFile) }
const atlasHeight = atlas[sheetId].h

const sprites = {}
for (const file of fs.readdirSync(rippedDir).filter((f) => f.endsWith(".json"))) {
  const data = JSON.parse(fs.readFileSync(path.join(rippedDir, file), "utf8"))
  const name = data.m_Name
  if (!includePatterns.some((pattern) => pattern.test(name))) continue

  const rect = data.m_RD?.m_TextureRect
  if (!rect || rect.m_Width <= 0 || rect.m_Height <= 0) continue

  sprites[spriteClassName(name)] = {
    name,
    sheet: sheetId,
    x: rect.m_X,
    y: rect.m_Y,
    w: rect.m_Width,
    h: rect.m_Height,
  }
}

if (Object.keys(sprites).length !== 5) {
  console.warn(
    `Expected 5 weapon sprites, found ${Object.keys(sprites).length}:`,
    Object.keys(sprites),
  )
}

fs.mkdirSync(publicDir, { recursive: true })
fs.copyFileSync(sheetFile, path.join(publicDir, `${sheetId}.png`))

fs.mkdirSync(path.dirname(outJson), { recursive: true })
fs.writeFileSync(outJson, JSON.stringify({ atlas, sprites, scale }, null, 2))

const sheetUrl = `url('${assetBase}sprites/${sheetId}.png')`
const lines = [
  "/* Generated by tools/build-weapon-memory-sprites.mjs - do not edit by hand. */",
  "/* W3Schools-style sprites: native atlas coords, no background-size. */",
  "",
  ":root {",
  `  --wm-sprite-scale: ${scale};`,
  "}",
  "",
  ".wm-sprite {",
  "  display: inline-block;",
  "  flex: 0 0 auto;",
  "  background-repeat: no-repeat;",
  "  image-rendering: pixelated;",
  "  transform: scale(var(--wm-sprite-scale));",
  "  transform-origin: top left;",
  "}",
  "",
]

const weaponOrder = ["censer", "sword", "rapier", "meaculpa", "whip"]
for (const className of weaponOrder) {
  const rect = sprites[className]
  if (!rect) continue
  const cssX = rect.x
  const cssY = atlasHeight - rect.y - rect.h
  lines.push(
    `.wm-sprite--${className} {`,
    `  width: ${rect.w}px;`,
    `  height: ${rect.h}px;`,
    `  background-image: ${sheetUrl};`,
    `  background-position: ${-cssX}px ${-cssY}px;`,
    "}",
    "",
  )
}

fs.writeFileSync(outCss, lines.join("\n"))

console.log(`Wrote ${Object.keys(sprites).length} weapon memory sprites`)
console.log(`JSON -> ${outJson}`)
console.log(`CSS  -> ${outCss}`)
