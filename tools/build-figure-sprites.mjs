import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const [
  rippedDir = path.join(
    __dirname,
    "../../ripped/Assets/#Art/Sprites/UI/Argent Board",
  ),
  outJson = path.join(__dirname, "../src/data/figure-sprites.json"),
  outCss = path.join(__dirname, "../src/styles/figure-sprites.css"),
  publicDir = path.join(__dirname, "../public/sprites"),
  assetBase = "/blasphemous2-save-analyzer/",
  scaleRaw = "1.5",
] = process.argv.slice(2)

const scale = Number(scaleRaw)

const sheets = {
  "cab-0e1f39bc4663c7e421de0d93a0915123": "argent-board-figures",
  "cab-4efffc4c7d9fc8de37078161897ee3af": "argent-board-figures-2",
}

function pngSize(file) {
  const buf = fs.readFileSync(file)
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

const assetsDir = path.join(rippedDir, "../../../..")

const sheetFiles = {
  "argent-board-figures": path.join(
    rippedDir,
    "argent-board-figures-spritesheet.png",
  ),
  "argent-board-figures-2": path.join(
    rippedDir,
    "argent-board-figures-2-spritesheet.png",
  ),
  "burn-board-figures": path.join(
    assetsDir,
    "Texture2D/burn-board-figures.png",
  ),
}

const burnJsonDir = path.join(assetsDir, "Sprite")

const atlas = {}
for (const [id, file] of Object.entries(sheetFiles)) {
  atlas[id] = pngSize(file)
}

const sprites = {}
for (const file of fs.readdirSync(rippedDir)) {
  const m = file.match(/^(FG\d+)-(base|resonance|empty|full)\.json$/)
  if (!m) continue
  const id = m[1]
  const variant = m[2]
  const data = JSON.parse(fs.readFileSync(path.join(rippedDir, file), "utf8"))
  const rect = data.m_RD?.m_TextureRect
  const collection = data.m_RD?.m_Texture?.m_Collection
  if (!rect || rect.m_Width <= 0 || rect.m_Height <= 0) continue
  const sheet = sheets[collection]
  if (!sheet) continue
  sprites[id] ??= {}
  sprites[id][variant] = {
    sheet,
    x: rect.m_X,
    y: rect.m_Y,
    w: rect.m_Width,
    h: rect.m_Height,
  }
}

if (fs.existsSync(burnJsonDir)) {
  for (const file of fs.readdirSync(burnJsonDir)) {
    const m = file.match(/^(FG\d+)-burn\.json$/)
    if (!m) continue
    const id = m[1]
    const data = JSON.parse(fs.readFileSync(path.join(burnJsonDir, file), "utf8"))
    const rect = data.m_RD?.m_TextureRect
    if (!rect || rect.m_Width <= 0 || rect.m_Height <= 0) continue
    sprites[id] ??= {}
    sprites[id].burn = {
      sheet: "burn-board-figures",
      x: rect.m_X,
      y: rect.m_Y,
      w: rect.m_Width,
      h: rect.m_Height,
    }
  }
}

fs.mkdirSync(publicDir, { recursive: true })
for (const [id, file] of Object.entries(sheetFiles)) {
  if (!fs.existsSync(file)) continue
  fs.copyFileSync(file, path.join(publicDir, `${id}.png`))
}

fs.mkdirSync(path.dirname(outCss), { recursive: true })
fs.writeFileSync(outJson, JSON.stringify({ atlas, sprites, scale }, null, 2))

const sheetUrls = Object.fromEntries(
  Object.keys(sheetFiles)
    .filter((id) => fs.existsSync(sheetFiles[id]))
    .map((id) => [id, `url('${assetBase}sprites/${id}.png')`]),
)

const lines = [
  "/* Generated by tools/build-figure-sprites.mjs - do not edit by hand. */",
  "/* W3Schools-style sprites: native atlas coords, no background-size. */",
  "",
  ":root {",
  `  --figure-sprite-scale: ${scale};`,
  "  --figure-sprite-native-width: 38px;",
  "  --figure-sprite-native-height: 80px;",
  `  --figure-sprite-width: calc(var(--figure-sprite-native-width) * ${scale});`,
  `  --figure-sprite-height: calc(var(--figure-sprite-native-height) * ${scale});`,
  "}",
  "",
  ".fg-sprite {",
  "  width: var(--figure-sprite-native-width);",
  "  height: var(--figure-sprite-native-height);",
  "  display: block;",
  "  flex: 0 0 auto;",
  "  background-repeat: no-repeat;",
  "  image-rendering: pixelated;",
  "}",
  "",
]

for (const [id, variants] of Object.entries(sprites).sort(([a], [b]) =>
  a.localeCompare(b, undefined, { numeric: true }),
)) {
  for (const [variant, rect] of Object.entries(variants).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    if (!atlas[rect.sheet]) continue
    // Unity texture rects use a bottom-left origin; CSS background-position
    // uses a top-left origin, so flip Y against the atlas height.
    const atlasHeight = atlas[rect.sheet].h
    const cssX = rect.x
    const cssY = atlasHeight - rect.y - rect.h
    lines.push(
      `.fg-sprite--${id}--${variant} {`,
      `  background-image: ${sheetUrls[rect.sheet]};`,
      `  background-position: ${-cssX}px ${-cssY}px;`,
      "}",
      "",
    )
  }
}

fs.writeFileSync(outCss, lines.join("\n"))

const variantCount = Object.values(sprites).reduce(
  (sum, entry) => sum + Object.keys(entry).length,
  0,
)
console.log(
  `Wrote ${Object.keys(sprites).length} figures with ${variantCount} variants`,
)
console.log(`JSON -> ${outJson}`)
console.log(`CSS  -> ${outCss}`)
