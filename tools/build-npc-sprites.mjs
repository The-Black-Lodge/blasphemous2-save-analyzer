import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const [
  sourceDir = path.join(
    __dirname,
    "../../AssetRipper_export_20260621_154214/ExportedProject/Assets/#Art/Sprites/NPCs/NPC12 - Cobijadas",
  ),
  outJson = path.join(__dirname, "../src/data/npc-sprites.json"),
  outCss = path.join(__dirname, "../src/styles/npc-sprites.css"),
  publicDir = path.join(__dirname, "../public/sprites"),
  assetBase = "/blasphemous2-save-analyzer/",
  scaleRaw = "2",
] = process.argv.slice(2)

const scale = Number(scaleRaw)

const sheetId = "NPCCobijada-act"
const spritesToInclude = [
  { className: "cobijada", assetFile: "NPCCobijada-act_0.asset" },
]

function pngSize(file) {
  const buf = fs.readFileSync(file)
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

function parseSpriteAsset(file) {
  const text = fs.readFileSync(file, "utf8")
  const name = text.match(/^\s*m_Name:\s*(.+)$/m)?.[1]?.trim()
  const rectBlock =
    text.match(
      /textureRect:\s*\n\s*x:\s*(\d+)\s*\n\s*y:\s*(\d+)\s*\n\s*width:\s*(\d+)\s*\n\s*height:\s*(\d+)/,
    ) ??
    text.match(
      /m_Rect:\s*\n(?:\s*\S+:\s*\S+\s*\n)*?\s*x:\s*(\d+)\s*\n\s*y:\s*(\d+)\s*\n\s*width:\s*(\d+)\s*\n\s*height:\s*(\d+)/,
    )
  if (!rectBlock) return null
  return {
    name,
    x: Number(rectBlock[1]),
    y: Number(rectBlock[2]),
    w: Number(rectBlock[3]),
    h: Number(rectBlock[4]),
  }
}

const sheetFile = path.join(sourceDir, `${sheetId}.png`)
if (!fs.existsSync(sheetFile)) {
  console.error("Missing atlas:", sheetFile)
  process.exit(1)
}

const atlas = { [sheetId]: pngSize(sheetFile) }
const atlasHeight = atlas[sheetId].h

const sprites = {}
for (const entry of spritesToInclude) {
  const assetPath = path.join(sourceDir, entry.assetFile)
  if (!fs.existsSync(assetPath)) {
    console.error("Missing sprite asset:", assetPath)
    process.exit(1)
  }
  const rect = parseSpriteAsset(assetPath)
  if (!rect) {
    console.error("Could not parse sprite rect:", assetPath)
    process.exit(1)
  }
  sprites[entry.className] = {
    name: rect.name,
    sheet: sheetId,
    x: rect.x,
    y: rect.y,
    w: rect.w,
    h: rect.h,
  }
}

fs.mkdirSync(publicDir, { recursive: true })
fs.copyFileSync(sheetFile, path.join(publicDir, `${sheetId}.png`))

fs.mkdirSync(path.dirname(outJson), { recursive: true })
fs.writeFileSync(outJson, JSON.stringify({ atlas, sprites, scale }, null, 2))

const sheetUrl = `url('${assetBase}sprites/${sheetId}.png')`
const lines = [
  "/* Generated by tools/build-npc-sprites.mjs - do not edit by hand. */",
  "/* W3Schools-style sprites: native atlas coords, no background-size. */",
  "",
  ":root {",
  `  --npc-sprite-scale: ${scale};`,
  "}",
  "",
  ".npc-sprite {",
  "  display: inline-block;",
  "  flex: 0 0 auto;",
  "  background-repeat: no-repeat;",
  "  image-rendering: pixelated;",
  "  transform: scale(var(--npc-sprite-scale));",
  "  transform-origin: top left;",
  "}",
  "",
]

for (const [className, rect] of Object.entries(sprites).sort(([a], [b]) =>
  a.localeCompare(b, undefined, { numeric: true }),
)) {
  const cssX = rect.x
  const cssY = atlasHeight - rect.y - rect.h
  lines.push(
    `.npc-sprite--${className} {`,
    `  width: ${rect.w}px;`,
    `  height: ${rect.h}px;`,
    `  background-image: ${sheetUrl};`,
    `  background-position: ${-cssX}px ${-cssY}px;`,
    "}",
    "",
  )
}

fs.writeFileSync(outCss, lines.join("\n"))

console.log(`Wrote ${Object.keys(sprites).length} NPC sprites`)
console.log(`JSON -> ${outJson}`)
console.log(`CSS  -> ${outCss}`)
