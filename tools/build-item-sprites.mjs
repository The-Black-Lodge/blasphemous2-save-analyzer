import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const [
  rippedDir = path.join(
    __dirname,
    "../../ripped/Assets/#Art/Sprites/Items",
  ),
  outJson = path.join(__dirname, "../src/data/item-sprites.json"),
  outCss = path.join(__dirname, "../src/styles/item-sprites.css"),
  publicDir = path.join(__dirname, "../public/sprites"),
  assetBase = "/blasphemous2-save-analyzer/",
  scaleRaw = "2",
] = process.argv.slice(2)

const scale = Number(scaleRaw)

const sheets = {
  "cab-0889fdf498740612328d98a5c31e6c38": "items-spritesheet",
  "cab-d9b784f3f1286d22490649afc43b8e5a": "items-spritesheet-dlc",
}

function pngSize(file) {
  const buf = fs.readFileSync(file)
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

const atlasFiles = {
  "items-spritesheet": path.join(rippedDir, "items-spritesheet.png"),
  "items-spritesheet-dlc": path.join(rippedDir, "items-spritesheet-dlc.png"),
  "items-spritesheet-dlc2": path.join(rippedDir, "items-spritesheet-dlc2.png"),
}

const atlas = {}
for (const [id, file] of Object.entries(atlasFiles)) {
  if (!fs.existsSync(file)) {
    console.warn("Missing atlas:", file)
    continue
  }
  atlas[id] = pngSize(file)
}

const sprites = {}
const jsonFiles = fs.readdirSync(rippedDir).filter((f) => /^RB\d+\.json$/.test(f))
for (const file of jsonFiles) {
  const rbId = file.replace(/\.json$/, "")
  const data = JSON.parse(fs.readFileSync(path.join(rippedDir, file), "utf8"))
  const rect = data.m_RD?.m_TextureRect
  const collection = data.m_RD?.m_Texture?.m_Collection
  if (!rect || rect.m_Width <= 0 || rect.m_Height <= 0) continue
  const sheet = sheets[collection]
  if (!sheet) continue
  sprites[rbId] = {
    sheet,
    x: rect.m_X,
    y: rect.m_Y,
    w: rect.m_Width,
    h: rect.m_Height,
    uvW: data.m_RD?.m_UvTransform?.m_W ?? 0,
  }
}

// RB101–RB106 art lives on items-spritesheet-dlc.png row 5 (same cells as RB201–RB206).
// Ripped JSON still points at the main atlas, which only has placeholder labels there.
for (let i = 1; i <= 6; i++) {
  const beadId = `RB10${i}`
  const dlcId = `RB20${i}`
  if (!sprites[dlcId]) continue
  sprites[beadId] = { ...sprites[dlcId], sheet: "items-spritesheet-dlc" }
}

fs.mkdirSync(publicDir, { recursive: true })
for (const [id, file] of Object.entries(atlasFiles)) {
  if (!fs.existsSync(file)) continue
  fs.copyFileSync(file, path.join(publicDir, `${id}.png`))
}

fs.mkdirSync(path.dirname(outJson), { recursive: true })
fs.writeFileSync(outJson, JSON.stringify({ atlas, sprites, scale }, null, 2))

const sheetUrls = Object.fromEntries(
  Object.keys(atlasFiles)
    .filter((id) => fs.existsSync(atlasFiles[id]))
    .map((id) => [id, `url('${assetBase}sprites/${id}.png')`]),
)

const lines = [
  "/* Generated by tools/build-item-sprites.mjs — do not edit by hand. */",
  "/* W3Schools-style sprites: native atlas coords, no background-size. */",
  "",
  ":root {",
  `  --rb-sprite-scale: ${scale};`,
  "  --rb-sprite-native-size: 30px;",
  `  --rb-sprite-size: calc(var(--rb-sprite-native-size) * ${scale});`,
  "}",
  "",
  ".rb-sprite {",
  "  width: var(--rb-sprite-native-size);",
  "  height: var(--rb-sprite-native-size);",
  "  display: inline-block;",
  "  flex: 0 0 auto;",
  "  background-repeat: no-repeat;",
  "  image-rendering: pixelated;",
  "}",
  "",
]

for (const [id, rect] of Object.entries(sprites).sort(([a], [b]) =>
  a.localeCompare(b, undefined, { numeric: true }),
)) {
  if (!atlas[rect.sheet]) continue
  const atlasHeight = atlas[rect.sheet].h
  const cssX = rect.x
  // Unity texture rects use a bottom-left origin; CSS uses top-left.
  // DLC item slices expose the CSS row in m_UvTransform.m_W (see RB201: m_W=150 → y=120).
  const cssY =
    rect.sheet.includes("dlc") && rect.uvW > 0
      ? rect.uvW - rect.h
      : atlasHeight - rect.y - rect.h
  lines.push(
    `.rb-sprite--${id} {`,
    `  background-image: ${sheetUrls[rect.sheet]};`,
    `  background-position: ${-cssX}px ${-cssY}px;`,
    "}",
    "",
  )
}

fs.writeFileSync(outCss, lines.join("\n"))

console.log(`Wrote ${Object.keys(sprites).length} rosary sprites`)
console.log(`JSON -> ${outJson}`)
console.log(`CSS  -> ${outCss}`)
