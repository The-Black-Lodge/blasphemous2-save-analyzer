import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const [
  spriteJsonDir = path.join(
    __dirname,
    "../../ripped/Assets/#Art/Sprites/UI/Argent Board",
  ),
  atlasFile = path.join(
    __dirname,
    "../../ripped/Assets/#Art/Sprites/UI/Argent Board/argent-board-stats-spritesheet.png",
  ),
  outCss = path.join(__dirname, "../src/styles/figure-category-sprites.css"),
  publicDir = path.join(__dirname, "../public/sprites"),
  assetBase = "/blasphemous2-save-analyzer/",
  scaleRaw = "2",
] = process.argv.slice(2)

const scale = Number(scaleRaw)
const sheetId = "argent-board-stats"
const kinds = [
  "erudition",
  "punishment",
  "faith",
  "pilgrimage",
  "empty",
  "grace",
]

function pngSize(file) {
  const buf = fs.readFileSync(file)
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

const atlas = pngSize(atlasFile)
const sprites = {}

for (const kind of kinds) {
  const jsonFile = path.join(spriteJsonDir, `argent-board-cat-${kind}.json`)
  if (!fs.existsSync(jsonFile)) {
    console.warn("Missing", jsonFile)
    continue
  }
  const data = JSON.parse(fs.readFileSync(jsonFile, "utf8"))
  const rect = data.m_RD?.m_TextureRect
  if (!rect || rect.m_Width <= 0 || rect.m_Height <= 0) continue
  sprites[kind] = {
    x: rect.m_X,
    y: rect.m_Y,
    w: rect.m_Width,
    h: rect.m_Height,
  }
}

fs.mkdirSync(publicDir, { recursive: true })
fs.copyFileSync(
  atlasFile,
  path.join(publicDir, `${sheetId}.png`),
)

const sheetUrl = `url('${assetBase}sprites/${sheetId}.png')`
const lines = [
  "/* Generated by tools/build-category-sprites.mjs — do not edit by hand. */",
  "",
  ":root {",
  `  --figure-cat-sprite-scale: ${scale};`,
  "  --figure-cat-sprite-native-size: 18px;",
  `  --figure-cat-sprite-size: calc(var(--figure-cat-sprite-native-size) * ${scale});`,
  "}",
  "",
  ".fg-cat-sprite {",
  "  width: var(--figure-cat-sprite-native-size);",
  "  height: var(--figure-cat-sprite-native-size);",
  "  display: inline-block;",
  "  flex: 0 0 auto;",
  "  background-image: " + sheetUrl + ";",
  "  background-repeat: no-repeat;",
  "  image-rendering: pixelated;",
  "}",
  "",
]

for (const [kind, rect] of Object.entries(sprites)) {
  const cssY = atlas.h - rect.y - rect.h
  lines.push(
    `.fg-cat-sprite--${kind} {`,
    `  background-position: ${-rect.x}px ${-cssY}px;`,
    "}",
    "",
  )
}

fs.mkdirSync(path.dirname(outCss), { recursive: true })
fs.writeFileSync(outCss, lines.join("\n"))
console.log(`Wrote ${Object.keys(sprites).length} category sprites to ${outCss}`)
