import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

const sourceSheet = path.join(
  __dirname,
  "../../AssetRipper_export_20260621_154214/ExportedProject/Assets/#Art/Fonts/spritesheets/symbol.png",
)
const sourceAsset = path.join(
  __dirname,
  "../../AssetRipper_export_20260621_154214/ExportedProject/Assets/#Art/Fonts/spritesheets/symbol_0.asset",
)
const outCss = path.join(__dirname, "../src/styles/symbol-sprites.css")
const publicDir = path.join(__dirname, "../public/sprites")
const assetBase = "/blasphemous2-save-analyzer/"
const scaleRaw = process.argv[2] ?? "3"

const scale = Number(scaleRaw)
const sheetId = "symbol"

function pngSize(file) {
  const buf = fs.readFileSync(file)
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
}

function parseSpriteAsset(file) {
  const text = fs.readFileSync(file, "utf8")
  const rectBlock =
    text.match(
      /textureRect:\s*\n\s*x:\s*(\d+)\s*\n\s*y:\s*(\d+)\s*\n\s*width:\s*(\d+)\s*\n\s*height:\s*(\d+)/,
    ) ??
    text.match(
      /m_Rect:\s*\n\s*serializedVersion: \d+\s*\n\s*x:\s*(\d+)\s*\n\s*y:\s*(\d+)\s*\n\s*width:\s*(\d+)\s*\n\s*height:\s*(\d+)/,
    )
  if (!rectBlock) return null
  return {
    x: Number(rectBlock[1]),
    y: Number(rectBlock[2]),
    w: Number(rectBlock[3]),
    h: Number(rectBlock[4]),
  }
}

if (!fs.existsSync(sourceSheet)) {
  console.error("Missing atlas:", sourceSheet)
  process.exit(1)
}

const atlas = pngSize(sourceSheet)
const rect = parseSpriteAsset(sourceAsset)
if (!rect) {
  console.error("Could not parse sprite rect:", sourceAsset)
  process.exit(1)
}

fs.mkdirSync(publicDir, { recursive: true })
fs.copyFileSync(sourceSheet, path.join(publicDir, `${sheetId}.png`))

const sheetUrl = `url('${assetBase}sprites/${sheetId}.png')`
const cssX = rect.x
const cssY = atlas.h - rect.y - rect.h

const lines = [
  "/* Generated by tools/build-symbol-sprites.mjs — do not edit by hand. */",
  "",
  ":root {",
  `  --symbol-sprite-scale: ${scale};`,
  "}",
  "",
  ".symbol-sprite {",
  "  display: inline-block;",
  "  flex: 0 0 auto;",
  "  background-repeat: no-repeat;",
  "  image-rendering: pixelated;",
  "  transform: scale(var(--symbol-sprite-scale));",
  "  transform-origin: top left;",
  `  width: ${rect.w}px;`,
  `  height: ${rect.h}px;`,
  `  background-image: ${sheetUrl};`,
  `  background-position: ${-cssX}px ${-cssY}px;`,
  "}",
  "",
]

fs.writeFileSync(outCss, lines.join("\n"))

console.log(`Wrote symbol sprite (${rect.w}x${rect.h} @ ${cssX},${cssY})`)
console.log(`CSS -> ${outCss}`)
